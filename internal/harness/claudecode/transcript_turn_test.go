// Transcript lines in the shapes Claude Code 2.1.330 writes them.
const (
	reminded  = `{"type":"user","isSidechain":false,"message":{"role":"user","content":"<system-reminder>\nLinked sessions now.\n</system-reminder>\n\nFix the checkout totals"}}`
	caveat    = `{"type":"user","isSidechain":false,"isMeta":true,"message":{"role":"user","content":"Caveat: the messages below were generated by the user while running local commands."}}`
	command   = `{"type":"user","isSidechain":false,"message":{"role":"user","content":"<command-name>/model</command-name>"}}`
	toolUse   = `{"type":"assistant","isSidechain":false,"message":{"stop_reason":"tool_use","content":[{"type":"tool_use","name":"Bash"}]}}`
	result    = `{"type":"user","isSidechain":false,"message":{"role":"user","content":[{"type":"tool_result","content":"ok"}]}}`
	endTurn   = `{"type":"assistant","isSidechain":false,"message":{"stop_reason":"end_turn","content":[{"type":"text","text":"Done."}]}}`
	summary   = `{"type":"system","subtype":"stop_hook_summary","isSidechain":false,"hookCount":2}`
	latch     = `{"type":"atis-latch"}`
	stopped   = `{"type":"user","isSidechain":false,"message":{"role":"user","content":[{"type":"text","text":"[Request interrupted by user for tool use]"}]}}`
	sideEnded = `{"type":"assistant","isSidechain":true,"message":{"stop_reason":"end_turn","content":[]}}`
)

func transcript(t *testing.T, lines ...string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "s.jsonl")
	if err := os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

// The Engine asks whether a working Session's turn is over when no Stop hook
// said so: the transcript's last main entry tells.
func TestTheTranscriptTellsWhetherATurnIsOver(t *testing.T) {
	for _, c := range []struct {
		name  string
		lines []string
		ended bool
	}{
		{"ended, with the hooks' summary", []string{reminded, toolUse, result, endTurn, summary, latch}, true},
		{"ended, before the summary", []string{reminded, endTurn}, true},
		{"stopped by the human", []string{reminded, toolUse, stopped}, true},
		{"calling a tool", []string{reminded, toolUse}, false},
		{"after a tool's result", []string{reminded, toolUse, result}, false},
		{"a subagent ended, the main turn did not", []string{reminded, toolUse, sideEnded}, false},
	} {
		t.Run(c.name, func(t *testing.T) {
			ended, written, ok := claudecode.Runner{}.TurnOver(transcript(t, c.lines...))
			if !ok || ended != c.ended || written.IsZero() {
				t.Errorf("TurnOver = %v, %v, %v; want ended %v", ended, written, ok, c.ended)
			}
		})
	}
	if _, _, ok := (claudecode.Runner{}).TurnOver(filepath.Join(t.TempDir(), "none.jsonl")); ok {
		t.Error("a missing transcript was read")
	}
}

// A prompt records the transcript and the prompt the Session began on: the
// human's words in the transcript, without the reminders the desktop app puts
// before them, and never a command or a note Claude Code wrote.
func TestAPromptRecordsTheFirstPromptAndTheTranscript(t *testing.T) {
	c, dir := enginetest.Start(t)
	folder := t.TempDir()
	path := transcript(t, caveat, command, reminded, endTurn)
	ev := map[string]any{"session_id": "s1", "transcript_path": path, "cwd": folder, "hook_event_name": "UserPromptSubmit",
		"permission_mode": "default", "prompt": "And the tax line"}
	in, _ := json.Marshal(ev)
	hook(t, dir, in)
	s, err := c.Session(claudecode.HarnessName, "s1")
	if err != nil {
		t.Fatal(err)
	}
	if s.FirstPrompt != "Fix the checkout totals" || s.Transcript != path {
		t.Errorf("first prompt %q, transcript %q", s.FirstPrompt, s.Transcript)
	}

	// A Session's first prompt is not in its transcript yet: the one typed is it.
	ev["session_id"], ev["transcript_path"] = "s2", filepath.Join(folder, "new.jsonl")
	ev["prompt"] = "<system-reminder>\nnote\n</system-reminder>\nAdd a dark mode"
	in, _ = json.Marshal(ev)
	hook(t, dir, in)
	if s, _ := c.Session(claudecode.HarnessName, "s2"); s.FirstPrompt != "Add a dark mode" {
		t.Errorf("first prompt %q", s.FirstPrompt)
	}

	// A subagent's report is not one.
	ev["session_id"], ev["prompt"] = "s3", "<task-notification>done</task-notification>"
	in, _ = json.Marshal(ev)
	hook(t, dir, in)
	if s, _ := c.Session(claudecode.HarnessName, "s3"); s.FirstPrompt != "" {
		t.Errorf("first prompt %q", s.FirstPrompt)
	}
}

// A Session already running when Pong learned to read transcripts gives its
// transcript and first prompt at its first tool call, and leaves a mark so
// later calls do not ask the Engine again.
func TestTheFirstToolCallRecordsARunningSessionsTranscript(t *testing.T) {
	c, dir := enginetest.Start(t)
	path := transcript(t, reminded, toolUse)
	call := func() {
		in, _ := json.Marshal(map[string]any{"session_id": "running-1", "transcript_path": path, "cwd": t.TempDir(),
			"hook_event_name": "PreToolUse", "tool_name": "Bash", "tool_input": map[string]string{"command": "ls"}})
		hook(t, dir, in)
	}
	call()
	s, err := c.Session(claudecode.HarnessName, "running-1")
	if err != nil {
		t.Fatal(err)
	}
	if s.Transcript != path || s.FirstPrompt != "Fix the checkout totals" {
		t.Fatalf("transcript %q, first prompt %q", s.Transcript, s.FirstPrompt)
	}
	if _, err := os.Stat(filepath.Join(dir, claudecode.TranscriptsNoted, "running-1")); err != nil {
		t.Fatalf("no mark: %v", err)
	}
	// Marked, a later call leaves the Session as it is.
	os.WriteFile(path, []byte(endTurn+"\n"), 0o600)
	call()
	if s2, _ := c.Session(claudecode.HarnessName, "running-1"); !s2.UpdatedAt.Equal(s.UpdatedAt) {
		t.Error("a later tool call changed the Session")
	}
}
